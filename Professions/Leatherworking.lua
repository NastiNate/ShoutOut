        id = "lw" .. r[1], spell = r[1], item = r[2], skill = r[3],
        slot = byCode[r[4]], quality = r[5],
        -- Other (tools, cured leather) stays out of the starter ads
        starter = r[4] ~= "O" and r[5] >= 3,
    }
end

ns.RegisterProfession({
    key = "leatherworking", name = "Leatherworking", fallback = "Leatherworker", icon = "Interface\\Icons\\Trade_LeatherWorking",
    kind = "item", listToken = "{items}", extras = "lwExtras",
    starterPerSection = 1, -- the starter ad checks the best item of each section in its message
    sections = SECTIONS, entries = entries,
    -- an example of text between groups; "||" posts as a double pipe
    defaultTemplate = "{prof} LFW | {items:Armor Kits} | WTS {items:Cloak} {items:Head} | Taking craft requests with your mats + tip, /w me",
    starterAds = {
        { name = "New ad", minSkill = 0, maxSkill = 999 }, -- best 3 kits and 3 cloaks
    },
})
